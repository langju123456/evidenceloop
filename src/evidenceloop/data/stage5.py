"""D16, stage 5: preference pairs and DPO on C's tasks, and the harder test split.

Three arms from W25, seeds 1, 2, 3: C (stage 4's SFT adapters, not retrained), P (DPO only) and CP (C merged into
W25, then DPO on the same pairs as P).

Hard split: test_hard and calib_hard are generated by the unchanged generator from their own seed ranges
(tasks/generator.py). hard_problems() checks that every task has the D16 difficulty and that the reference solver
solves it in either order; key_overlaps() checks that no task content is shared with the four official splits or
with any task already trained on. The record goes to configs/frozen_hard.json, apart from configs/frozen.json.

build_seed(): C_s is rebuilt exactly as stage 4 built it (stage4.build_seed), with all six frozen splits and the
warm-up tasks excluded; its aligned training file must hash to what configs/stage4.json records, which is the
file the C adapters were trained on. The pairs come from those same 100 tasks (data/prefs.py): half as many pairs
as C_s has samples, so P runs as many sequences with gradients as C did, and at 8 pairs per step as many steps.

gate(): before any training, C1-C3 on calib_hard must land between 20% and 90% together. Above that the split is
at the ceiling again, below it at the floor, and stage 5 stops (D16).
"""

