def build_seed(seed: int, n_tasks: int, evals: list[dict[str, Any]], exclude: set[str],
               source: prefs.Source | None = None) -> dict[str, Any]:
    """C_s as stage 4 built it, and the pairs for P_s and CP_s from the same tasks. Raises ValueError when stage 4's
    own checks fail or there are too few pairs."""
    result = stage4.build_seed(seed, n_tasks, evals, exclude)
    c = result["built"]["C"]
    c_samples = result["matched"]["samples"][f"C{seed}"]
    kept = {r["task_id"] for r in c["records"]}
    orders = {r["task_id"]: r["demo_order"] for r in c["records"]}
    tasks = [t for t in c["tasks"] if t["task_id"] in kept]
    candidates = prefs.build_pairs(tasks, c["privates"], orders, source or prefs.ScriptedSource())
    pairs = prefs.select_pairs(candidates["pairs"], len(c_samples) // 2, seed)
    leaked = {p["dedup_key"] for p in pairs} & exclude
    if leaked:
        raise ValueError(f"有 {len(leaked)} 道偏好对的题在冻结划分或预热数据里")
    return {
        "c_trl_sha256": jsonl_sha256([to_format(s, "trl") for s in c_samples]),
        "c_samples": len(c_samples),
        "c_task_ids": [r["task_id"] for r in c["records"]],
        "candidates": candidates,
        "pairs": pairs,
    }


def seed_summary(seed: int, result: dict[str, Any], trl_sha256: str) -> dict[str, Any]:
    pairs, candidates = result["pairs"], result["candidates"]
    per_task = Counter(Counter(p["task_id"] for p in pairs).values())
    return {
        "c_trl_sha256": result["c_trl_sha256"],  # must be the file C_s was trained on (configs/stage4.json)
        "c_samples": result["c_samples"],
        "tasks": len(result["c_task_ids"]),
        "attempts": candidates["attempts"],
        "passed_gate": candidates["passed_gate"],
        "candidate_pairs": len(candidates["pairs"]),
        "reject_counts": candidates["reject_counts"],
        "pairs": len(pairs),
        "sequences": 2 * len(pairs),
        "optimizer_steps": steps_for(len(pairs), 1, PAIRS_PER_STEP),
        "pairs_per_task": {str(k): v for k, v in sorted(per_task.items())},
        "tasks_with_pairs": len({p["task_id"] for p in pairs}),
        "composition": prefs.composition(pairs),
        "supervised_chars": {side: sum(supervised_size({"completion": p[side]}) for p in pairs) for side in ("chosen", "rejected")},
        "trl_sha256": trl_sha256,
    }


