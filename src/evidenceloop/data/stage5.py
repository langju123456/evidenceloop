def training_problems(log: dict[str, Any], data_sha256: str, base_fingerprint: str | None, seed: int,
                      adapter_fingerprint: str | None) -> list[str]:
    """Whether a finished DPO run is the D16 run for these pairs and this base (used to skip it on a resume)."""
    problems = []
    if log.get("loss") != "dpo":
        problems.append("不是 DPO 的训练日志")
    if log.get("aborted"):
        problems.append(f"训练中途停下：{log['aborted']}")
    if not log.get("adapter_fingerprint") or log.get("adapter_fingerprint") != adapter_fingerprint:
        problems.append("adapter 和训练日志对不上")
    if log.get("data_sha256") != data_sha256:
        problems.append("偏好对不是这一份")
    if base_fingerprint and log.get("base_fingerprint") != base_fingerprint:
        problems.append("起点（也就是 reference）不是指定的那个模型")
    if log.get("skipped"):
        problems.append(f"有偏好对因为太长被跳过：{log['skipped']}")
    cfg = log.get("config", {})
    wanted = dict(D16_TRAINING, seed=seed)
    wrong = {k: cfg.get(k) for k, v in wanted.items() if cfg.get(k) != v}
    if wrong:
        problems.append(f"训练设置和 D12、D16 不一样：{wrong}")
    return problems


def gate(rows: dict[int, list[dict[str, Any]] | None], seeds: tuple[int, ...] = SEEDS,
         expected_n: int = HARD_SIZES["calib_hard"], success_range: tuple[float, float] = GATE_RANGE) -> dict[str, Any]:
    """D16's difficulty check on C's calib_hard runs. Raises ValueError unless every seed has one complete run."""
    problems = []
    for seed in seeds:
        evals = rows.get(seed)
        if evals is None:
            problems.append(f"C{seed}：没有结果文件")
            continue
        problems += [f"C{seed}：{p}" for p in run_problems(evals, "calib_hard", expected_n)]
    if problems:
        raise ValueError("；".join(problems))
    successes = {seed: sum(1 for e in rows[seed] if e["task_success"]) for seed in seeds}
    rate = sum(successes.values()) / (expected_n * len(seeds))
    low, high = success_range
    reasons = []
    if rate > high:
        reasons.append(f"C 在 calib_hard 上的成功率 {rate:.1%} 高于 {high:.0%}：还是到顶，分不出差别")
    if rate < low:
        reasons.append(f"C 在 calib_hard 上的成功率 {rate:.1%} 低于 {low:.0%}：太难，分不出差别")
    return {"successes": successes, "n": expected_n, "rate": rate, "passed": not reasons, "reasons": reasons,
            "success_range": list(success_range)}


def render_gate(result: dict[str, Any], title: str = "阶段五的难度检查（D16）") -> str:
    low, high = result["success_range"]
    verdict = "通过" if result["passed"] else "不通过：" + "；".join(result["reasons"])
    total = sum(result["successes"].values())
    lines = [f"# {title}", "",
             f"- 结论：{verdict}",
             f"- C 在 calib_hard 上的成功率：{total}/{result['n'] * len(result['successes'])}（{result['rate']:.1%}），要求 {low:.0%}–{high:.0%}",
             "- calib_hard 和 test_hard 是同一分布的不同题，只用来确认难度；不通过就不训练，另记决策重新定难度。",
             "", "| 行 | 成功 |", "| --- | --- |"]
    lines += [f"| C{seed} | {ok}/{result['n']} |" for seed, ok in result["successes"].items()]
    return "\n".join(lines) + "\n"
