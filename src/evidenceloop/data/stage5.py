SEEDS = stage4.SEEDS  # the same replicate seeds, so P_s and CP_s train on C_s's tasks
N_TASKS = stage4.N_TASKS
HARD_SIZES = {"test_hard": 150, "calib_hard": 50}
# what a hard task may be made of: the training domain's own templates, schemas, units and failure, at the hard end
HARD_KNOBS = {"template": TRAIN_TEMPLATES, "schema": ("S1", "S2"), "units": ("all_mV", "mixed"), "n_versions": (4, 5),
              "error": ("transient",), "distractors": (3, 4)}
EVAL_SPLITS = ("test_hard", "test_id")  # what P and CP sit; W25 and C have their stage-4 runs on test_id
BETA = 0.1
PAIRS_PER_STEP = 8  # 16 sequences per optimizer step, as D12's 16 samples
# D12's settings as C used them, with the two things DPO adds
D16_TRAINING = dict(stage4.D12_TRAINING, grad_accum=PAIRS_PER_STEP, beta=BETA)
GATE_RANGE = (0.20, 0.90)
ARMS = {"C": "阶段四训好的 C：只做 SFT", "P": "只做 DPO：在 W25 上新建 LoRA",
        "CP": "SFT 之后接 DPO：C 合并进 W25，再新建 LoRA，偏好对和 P 相同"}


def hard_problems(split: str, publics: list[dict[str, Any]], privates: list[dict[str, Any]]) -> list[str]:
    """What is wrong with a hard split as generated; empty when it is the split D16 defines."""
    problems = []
    if len(publics) != HARD_SIZES[split] or len(privates) != len(publics):
        problems.append(f"{split} 有 {len(publics)} 道题，要求 {HARD_SIZES[split]} 道")
    if {p["generator_version"] for p in publics} != {GENERATOR_VERSION}:
        problems.append(f"{split} 不是用当前生成器 {GENERATOR_VERSION} 生成的")
    if {p["split"] for p in publics} != {split}:
        problems.append(f"{split} 里有别的划分的题")
    for knob, allowed in HARD_KNOBS.items():
        seen = {p["knobs"][knob] for p in publics}
        if not seen <= set(allowed):
            problems.append(f"{split} 的 {knob} 超出了 D16 的范围：{sorted(map(str, seen - set(allowed)))}")
    by_id = {p["task_id"]: p for p in privates}
    for order in prefs.ORDERS:
        for trace in run_episodes(publics, ScriptedBackend(order=order), max_turns=DEFAULT_MAX_TURNS):
            status = prefs.gate(trace, by_id[trace["task_id"]])
            if status != "passed":
                problems.append(f"{split} 的 {trace['task_id']} 参考解法（{order}）没有做对：{status}")
    return problems


def reference_turns(publics: list[dict[str, Any]]) -> dict[str, int]:
    """How many turns the reference solver needs, as {turns: tasks}."""
    turns = Counter(trace["turns"] for trace in run_episodes(publics, ScriptedBackend()))
    return {str(k): v for k, v in sorted(turns.items())}


def key_overlaps(keys: dict[str, set[str]], between: tuple[str, ...]) -> list[str]:
    """Shared dedup keys between each of `between` and every other named set."""
    found = []
    for i, name in enumerate(between):
        for other in list(between[i + 1:]) + [n for n in keys if n not in between]:
            shared = keys[name] & keys[other]
            if shared:
                found.append(f"{name} 和 {other} 有 {len(shared)} 道题内容重复")
    return found


